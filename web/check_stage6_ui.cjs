const {chromium,expect}=require('@playwright/test');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
  const manifest=JSON.parse(fs.readFileSync('.local/stage6-latest.json','utf8'));
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1080}});
  const errors=[],badResponses=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('response',response=>{if(response.status()>=400)badResponses.push(response.status()+' '+response.url());});
  const assets='docs/implementation/assets/stage6';fs.mkdirSync(assets,{recursive:true});
  const verified=[];
  for(const item of manifest.runs){
    const dir=`.local/runs/${item.run_id}/executions/${item.execution_id}`;
    const report=JSON.parse(fs.readFileSync(`${dir}/report.json`,'utf8'));
    await page.goto(`http://127.0.0.1:5173/?run=${item.run_id}&execution=${item.execution_id}`);
    await expect(page.locator('.run-progress')).toContainText(item.run_id);
    await expect(page.locator('.report-overview')).toContainText(item.execution_id);
    await expect(page.locator('.run-item.selected')).toContainText(item.run_id.slice(0,8));
    const metricText=await page.locator('.metrics').innerText();
    assert(metricText.includes(String(report.summary.planned)));
    assert(metricText.includes(String(report.summary.executed)));
    const group=page.getByRole('group',{name:'결과 필터'});
    await group.getByRole('button',{name:`실행 전체 ${report.summary.executed}`,exact:true}).click();
    await expect(page.locator('.case-card')).toHaveCount(report.summary.executed);
    const first=page.locator('.case-card').first();
    if(!await first.evaluate(element=>element.open))await first.locator(':scope > summary').click();
    await first.locator('.source > summary').click();
    await expect(first.locator('blockquote')).not.toBeEmpty();
    await expect(first.locator('.refs')).toContainText('requirements.md');
    await first.locator('.screenshot').first().click();
    const dialog=page.getByRole('dialog');await expect(dialog).toBeVisible();
    const image=dialog.locator('img');await expect(image).toBeVisible();
    await expect.poll(()=>image.evaluate(img=>img.complete&&img.naturalWidth>0)).toBe(true);
    assert((await image.getAttribute('src')).includes(`/runs/${item.run_id}/executions/${item.execution_id}/files/`));
    await page.keyboard.press('Escape');await expect(dialog).not.toBeVisible();
    await group.getByRole('button',{name:`미실행 ${report.summary.unexecuted}`,exact:true}).click();
    await expect(page.locator('.case-card.unsupported')).toHaveCount(report.summary.unexecuted);
    await group.getByRole('button',{name:`실행 전체 ${report.summary.executed}`,exact:true}).click();
    await page.locator('.report-overview').screenshot({path:`${assets}/run-${item.label}-summary.png`});
    await page.locator('.report-overview').scrollIntoViewIfNeeded();
    await page.screenshot({path:`${assets}/run-${item.label}-desktop.png`});
    verified.push({run_id:item.run_id,execution_id:item.execution_id,cases:report.summary.executed,unsupported:report.summary.unexecuted});
  }
  const a=manifest.runs[0];
  await page.locator('.run-item').filter({has:page.locator('code',{hasText:a.run_id.slice(0,8)})}).click();
  await expect(page.locator('.report-overview')).toContainText(a.execution_id);
  await page.setViewportSize({width:390,height:844});
  const widths=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
  assert(widths.scroll<=widths.client,JSON.stringify(widths));
  await page.locator('.report-overview').screenshot({path:`${assets}/results-mobile.png`});
  assert.deepEqual(errors,[]);assert.deepEqual(badResponses,[]);
  const result={runs:verified,history_switch:true,source:true,image_provenance:true,unsupported:true,mobile_no_overflow:true,page_errors:errors,failed_requests:badResponses};
  fs.writeFileSync('.local/stage6-ui-check.json',JSON.stringify(result,null,2));
  console.log('PASS: '+JSON.stringify(result));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
