const {chromium, expect} = require('@playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const latest=JSON.parse(fs.readFileSync('.local/stage5-latest.json','utf8'));
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const broken=[];page.on('response',response=>{if(response.status()>=400)broken.push(response.status()+' '+response.url());});
  await expect.poll(async()=>{try{return (await page.request.get('http://127.0.0.1:8000/api/health')).status();}catch{return 0;}},{timeout:30000}).toBe(200);
  await page.goto(`http://127.0.0.1:5173/?run=${latest.run_id}&execution=${latest.executions.email.execution_id}`);
  await expect(page.getByRole('heading',{name:'기획에서 실행 결과까지'})).toBeVisible();
  await page.locator('.run-item').filter({has:page.locator('code',{hasText:latest.run_id.slice(0,8)})}).click();
  await expect(page.getByLabel('실행 기록',{exact:true})).toBeVisible();
  async function select(mode) {
    const id=latest.executions[mode].execution_id;
    await page.getByLabel('실행 기록',{exact:true}).selectOption(id);
    await expect(page.locator('.report-overview')).toContainText(id);
  }
  await expect(page.locator('.report-overview')).toContainText(latest.executions.email.execution_id);
  await select('email');
  await expect(page.locator('.case-card.failed')).toHaveCount(1);
  await expect(page.locator('.case-card.failed .quadrant-label')).toHaveText('FN');
  await expect(page.locator('.case-card.failed .observed')).toContainText('이메일');
  await select('blank-accepted');
  await expect(page.locator('.case-card.failed .quadrant-label')).toHaveText('FP');
  await select('warning-color');
  const failed=page.locator('.case-card.failed');
  await expect(failed).toHaveCount(1);
  await expect(failed.locator('.quadrant-label')).toHaveText('TN');
  await expect(failed.locator('.assertion-error')).toContainText('Expected');
  await failed.locator('.source > summary').click();
  await expect(failed.locator('blockquote')).toContainText('빨간');
  await expect(failed.locator('.refs')).toContainText('문단 4');
  const image=failed.locator('.screenshot img').first();
  await expect(image).toBeVisible();
  assert(await image.evaluate(img=>img.complete && img.naturalWidth>0));
  await failed.locator('.screenshot').first().click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('dialog').locator('img')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button',{name:'미실행 170',exact:true}).click();
  await expect(page.locator('.case-card.unsupported')).toHaveCount(170);
  await page.locator('.case-card.unsupported').first().locator('summary').first().click();
  await expect(page.locator('.unsupported-reason').first()).toContainText('화면');
  await page.getByLabel('점검 검색').fill('BE_USER_002');
  assert(await page.locator('.case-card.unsupported').count()>0);
  assert(await page.locator('.case-card.unsupported').count()<170);
  await page.getByLabel('점검 검색').fill('존재하지않는테스트123');
  await expect(page.locator('.case-workspace .empty')).toBeVisible();
  await select('normal');
  await expect(page.locator('.case-card')).toHaveCount(20);
  await page.locator('.quadrants .TP').click();
  await expect(page.locator('.case-card')).toHaveCount(11);
  await page.getByRole('group',{name:'결과 필터'}).getByRole('button',{name:'정책 미확인 2',exact:true}).click();
  await expect(page.locator('.case-card')).toHaveCount(2);
  await page.locator('.case-card').first().locator('summary').first().click();
  await expect(page.locator('.case-card').first()).toContainText('명시적');
  await select('warning-position');
  await expect(page.locator('.case-card.failed .quadrant-label')).toHaveText('TN');
  await select('warning-color');
  const assets='docs/implementation/assets/stage5';fs.mkdirSync(assets,{recursive:true});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(assets,'results-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect(page.locator('.case-card.failed')).toBeVisible();
  const widths=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
  assert(widths.scroll<=widths.client,JSON.stringify(widths));
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(assets,'results-mobile.png'),fullPage:true});
  await page.locator('.preparation > summary').click();
  await expect(page.getByRole('button',{name:'생성부터 실행까지 시작',exact:true})).toBeEnabled();
  const setupWidths=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
  assert(setupWidths.scroll<=setupWidths.client,JSON.stringify(setupWidths));
  assert.deepEqual(errors,[]); assert.deepEqual(broken,[]);
  const result={history:true,deep_link:true,execution_switch:true,FN:true,FP:true,TN_visual_failure:true,source:true,screenshot_dialog:true,unsupported:170,search:true,quadrant_filter:true,unknown:2,mobile_no_overflow:true,console_errors:errors,failed_requests:broken};
  fs.writeFileSync('.local/stage5-ui-check.json',JSON.stringify(result,null,2));
  console.log('PASS: '+JSON.stringify(result));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
